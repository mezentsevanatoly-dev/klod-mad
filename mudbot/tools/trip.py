def say(*a):
    print(*a, flush=True)


def run(w, steps, rooms):
    for st in steps:
        kind = st[0]
        if kind == "cmd":
            w.c.send(st[1])
            w.pump(2.5)
            w.last_msdp_from_log()
        elif kind == "wait":
            t0 = time.time()
            while time.time() - t0 < 20 and w.cur["vnum"] != st[1]:
                w.pump(0.3)
                w.last_msdp_from_log()
            if w.cur["vnum"] != st[1]:
                say(f"ждали {st[1]}, мы в {w.cur['vnum']} {w.cur['name']}")
                return False
        elif kind == "swf":     # фиксированный спидволк (путь записан раз и навсегда, без поиска по графу)
            if w.cur["vnum"] != st[1]:
                say(f"старт {st[1]}, мы в {w.cur['vnum']} ({w.cur['name']}): иду goto")
                g.goto(w, st[1])
            say(f"спидволк {st[1]} -> {st[3]}: {st[2]}")
            if not w.speedwalk(st[2], st[3]):
                say(f"не дошли до {st[3]}, мы в {w.cur['vnum']} {w.cur['name']}")
                return False
        elif kind == "sw":
            a = w.cur["vnum"] if st[1] == "*" else st[1]
            if w.cur["vnum"] != a:
                say(f"старт {a}, мы в {w.cur['vnum']} ({w.cur['name']}): иду goto")
                g.goto(w, a)
            p = g.path(rooms, a, st[2])
            if p is None:
                say(f"нет пути {a} -> {st[2]}")
                return False
            sw = compress(p)
            say(f"спидволк {a} -> {st[2]}: {sw}")
            if not w.speedwalk(sw, st[2]):
                say(f"не дошли до {st[2]}, мы в {w.cur['vnum']} {w.cur['name']}")
                return False
    return True


def main():
    if len(sys.argv) < 2 or sys.argv[1] == "список":
        say("поездки:", ", ".join(TRIPS))
        say("места (в:<место>, из текущей комнаты):", ", ".join(PLACES))
        return
    w = Walker({})
    w.last_msdp_from_log()
    rooms = g.world()
    t0 = time.time()
    for name in sys.argv[1:]:
        if name.startswith("в:"):
            dest = name[2:]
            dest = dest if dest.isdigit() else PLACES[dest]             # в:226124 — любая комната по номеру (в т. ч. внутри инста)
            steps = [("sw", "*", dest)]
        else:
            steps = TRIPS[name]
        ok = run(w, steps, rooms)
        say(f"{name}: {'ok' if ok else 'ОШИБКА'} за {int(time.time() - t0)} с; мы в {w.cur['vnum']} {w.cur['area']} | {w.cur['name']}")
        if not ok:
            sys.exit(1)


if __name__ == "__main__":
    main()


